create table public.users (
  id uuid not null default gen_random_uuid (),
  email text null,
  gender text null,
  show_gender_public boolean null default true,
  location text null,
  languages text[] null,
  experience_level text null,
  preferred_distance text null,
  training_preference text null,
  open_for_training boolean null default false,
  open_for_travel boolean null default false,
  open_for_accommodation boolean null default false,
  pr_swim_1000m interval null,
  pr_bike_40km interval null,
  pr_run_5km interval null,
  pr_run_10km interval null,
  show_prs_public boolean null default false,
  profile_picture_url text null,
  bio text null,
  created_at timestamp with time zone null default now(),
  first_name text null,
  last_name text null,
  country_code text null,
  birth_date date null,
  show_birthdate boolean null default false,
  updated_at timestamp with time zone null,
  open_for_buddy boolean not null default true,
  constraint users_pkey primary key (id),
  constraint users_email_key unique (email)
) TABLESPACE pg_default;